-- =====================================================================
-- V1 - Criacao das tabelas do MVP de Fila de Atendimento
-- Banco: PostgreSQL 16 (scripts portaveis para H2 em modo PostgreSQL)
-- =====================================================================

CREATE TABLE filas (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                  VARCHAR(80)  NOT NULL,
    prefixo               VARCHAR(2)   NOT NULL,
    descricao             VARCHAR(255),
    ativa                 BOOLEAN      NOT NULL DEFAULT TRUE,
    ultima_sequencia      INTEGER      NOT NULL DEFAULT 0,
    data_ultima_sequencia DATE,
    criado_em             TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version               BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_filas_nome    UNIQUE (nome),
    CONSTRAINT uq_filas_prefixo UNIQUE (prefixo)
);

CREATE TABLE usuarios (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(120) NOT NULL,
    email         VARCHAR(150) NOT NULL,
    senha         VARCHAR(100) NOT NULL,
    perfil        VARCHAR(20)  NOT NULL,
    ativo         BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version       BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_usuarios_email UNIQUE (email),
    CONSTRAINT ck_usuarios_perfil CHECK (perfil IN ('USUARIO', 'ATENDENTE', 'ADMINISTRADOR'))
);

CREATE TABLE senhas (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fila_id                BIGINT      NOT NULL,
    numero                 VARCHAR(8)  NOT NULL,
    sequencia              INTEGER     NOT NULL,
    data_referencia        DATE        NOT NULL,
    status                 VARCHAR(20) NOT NULL,
    data_geracao           TIMESTAMP   NOT NULL,
    hora_chamada           TIMESTAMP,
    hora_inicio_atendimento TIMESTAMP,
    hora_fim_atendimento   TIMESTAMP,
    criado_em              TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em          TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version                BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT fk_senhas_fila FOREIGN KEY (fila_id) REFERENCES filas (id),
    CONSTRAINT uq_senhas_fila_data_sequencia UNIQUE (fila_id, data_referencia, sequencia),
    CONSTRAINT uq_senhas_fila_numero_data    UNIQUE (fila_id, numero, data_referencia),
    CONSTRAINT ck_senhas_status CHECK (status IN ('AGUARDANDO', 'CHAMADA', 'EM_ATENDIMENTO', 'ATENDIDA', 'CANCELADA'))
);

CREATE TABLE atendimentos (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    senha_id      BIGINT       NOT NULL,
    atendente_id  BIGINT,
    inicio        TIMESTAMP,
    fim           TIMESTAMP,
    guiche        VARCHAR(20),
    observacao    VARCHAR(500),
    criado_em     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_atendimentos_senha UNIQUE (senha_id),
    CONSTRAINT fk_atendimentos_senha FOREIGN KEY (senha_id) REFERENCES senhas (id),
    CONSTRAINT fk_atendimentos_atendente FOREIGN KEY (atendente_id) REFERENCES usuarios (id)
);

CREATE TABLE senha_eventos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    senha_id        BIGINT       NOT NULL,
    status_anterior VARCHAR(20),
    status_novo     VARCHAR(20)  NOT NULL,
    ocorrido_em     TIMESTAMP    NOT NULL,
    usuario_id      BIGINT,
    detalhe         VARCHAR(255),
    CONSTRAINT fk_senha_eventos_senha FOREIGN KEY (senha_id) REFERENCES senhas (id),
    CONSTRAINT fk_senha_eventos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);
